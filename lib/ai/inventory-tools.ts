export function getInventoryTool(name: string): InventoryToolDefinition | undefined {
  return INVENTORY_TOOLS.find(t => t.name === name)
}

export function getInventoryToolsForRole(role?: string): InventoryToolDefinition[] {
  if (!role) return []
  if (role === 'super_admin' || role === 'admin') return INVENTORY_TOOLS
  return INVENTORY_TOOLS.filter(t => {
    const viewRoles = ['inventory:dashboard:view', 'inventory:stock:read', 'inventory:products:read', 'inventory:suppliers:read']
    return viewRoles.includes(t.permission) || (role === 'manager' && ['inventory:procurement:purchase_request:create', 'inventory:procurement:purchase_order:create', 'inventory:procurement:reorder:manage', 'inventory:reports:view'].includes(t.permission))
  })
}
